// JavaScript Operators — Day 3
// A quick practice example for learning and sharing.

let english = 80;
let math = 58;
let science = 90;
let tamil = 39;
let social = 70;

let total = english + math + science + tamil + social;

console.log("Total:", total);
console.log("Average:", total / 5);
console.log("Multiplication:", english * total);
console.log("Division:", english / total);
console.log("Remainder:", english % total);
console.log("Exponentiation:", english ** 2);
console.log("Subtraction:", english - total);

// Comparison operators
let a = 10;
let b = 5;

console.log("Equal:", a == b);
console.log("Not equal:", a != b);
console.log("Strictly equal:", a === b);

console.log("Greater than:", a > b);
console.log("Less than:", a < b);
console.log("Greater than or equal:", a >= b);
console.log("Less than or equal:", a <= b);

// Increment and decrement operators
let e = 5;

console.log("Post-increment:", e++);
console.log("After increment:", e);

let f = 5;

console.log("Pre-increment:", ++f);
console.log("Current value:", f);

let g = 10;

console.log("Post-decrement:", g--);
console.log("After decrement:", g);

console.log("Pre-decrement:", --g);
console.log("Current value:", g);

